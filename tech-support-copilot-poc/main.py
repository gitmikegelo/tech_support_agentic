"""
CLI entry point for the Tech Support Copilot POC.

Run from the project root::

    python main.py

The CLI accepts customer messages typed by the rep, runs them through the
agentic orchestrator, and prints colour-coded output showing tool calls,
approval prompts, critic results, and the final suggestion.

Special commands
----------------
/trace      Print the path of the current JSONL trace file.
/evidence   Dump the evidence log accumulated this session.
/quit       End the session and close the trace file.
"""
